require('./register-ts.cjs')
const assert=require('node:assert/strict')
const {winterReceiptModel,verifyWinterReceipt,winterReceiptCoverage}=require('../lib/winter-receipts')
const {winterSettlementAccount}=require('../lib/winter-settlement')
const {allocateSettlement}=require('../lib/settlement-selection')
const {riderReceiptChoices}=require('../lib/rider-receipt')
const {winterPickerOrder}=require('../lib/winter-display-order')
const {WINTER_EVENT_ID:event_id}=require('../lib/winter-event')
const org=(id,name)=>({id,name,event_id})
const member=(id,organization_id,name)=>({id,name,organization_id,event_id})
const orgs=[org('z','フジファーム'),org('a','あおば')]
const people=[member('r2','z','同名'),member('r1','a','同名'),member('r3','z','阿部')]
const picker=winterPickerOrder(orgs,new Map([['r2','あい'],['r3','やま']]))
assert.deepEqual([...people].sort(picker).map(p=>p.id),['r1','r2','r3'])
const data={eventId:event_id,organizations:orgs,riders:people,horses:[member('h','z','テスト馬')],entries:[],competitions:[{event_id,id:'c',competition_no:'1',name:'競技'}]}
const initial=(id,riderId,entry_fee)=>({id,event_id,entry_fee,inputs:{organizationId:'a',billingOrganizationId:'z',competitionId:'c',horseId:'h',riderId}})
const ledger={initial:[initial('first','r1',6000),initial('second','r2',5000)],requests:[],advances:[{event_id,organization_key:'z',paid_amount:15000}],
payments:[{id:'p',event_id,organization_key:'z',amount:2000,payment_method:'cash_at_venue',note:'入金'}]}
const account=winterSettlementAccount(data,ledger,'z')
const model=winterReceiptModel(data,ledger,account,[])
assert.equal(model.availableAmount,17000)
assert.equal(model.sources.filter(i=>i.horseId==='h').length,3)
assert.equal(model.sources.filter(i=>!i.riderId).length,1)
assert.equal(model.scopeOptions.filter(o=>o.kind==='rider').length,2)
assert.deepEqual(winterReceiptModel(data,ledger,winterSettlementAccount(data,ledger,'a'),[]).sources,[])
assert.equal(winterReceiptCoverage(model,account,[],null).availableAmount,15000)
assert.equal(winterReceiptCoverage(model,account,[],14000).availableAmount,14000)
assert.equal(winterReceiptCoverage(model,{...account,total:13000},[],null).availableAmount,0)
const choices=riderReceiptChoices(model.sources,[])
const documentItems=allocateSettlement(choices,['normal:entry:first'],6000)
const issue=()=>({organization_key:'z',amount:6000,document_items:documentItems,selected_items:[]})
verifyWinterReceipt(issue(),model,[])
const receipt={event_id,organization_key:'z',amount:6000,document_items:documentItems}
const next=winterReceiptModel(data,ledger,account,[receipt])
assert.equal(next.availableAmount,11000)
assert.throws(()=>verifyWinterReceipt(issue(),next,[receipt]))
assert.throws(()=>winterReceiptModel(data,ledger,account,[{...receipt,organization_key:'a'}]))
assert.equal(winterReceiptModel(data,ledger,{...account,total:1500},[receipt]).availableAmount,0)
assert.equal(winterSettlementAccount(data,ledger,'z').remaining,8000)
console.log('PASS: club and kana order, distinct same-name riders, billed affiliation, shared horse fee counted once, group receipt limits, partial payment and reprint allocation')
