require('./register-ts.cjs')
const assert=require('node:assert/strict')
const fixture=require('./winter-application-fixture.cjs')
const {setup}=require('./winter-application-registration-fixture.cjs')
const {createApplicationDraft,readApplicationDraft}=require('../lib/winter-application-draft.ts')
const {applicationTodos,applicationClubSummary}=require('../lib/winter-application-guide.ts')
const {applicationPersonTarget,applicationEntryTarget}=require('../lib/master/application-guide.ts')
const app=fixture(),draft=createApplicationDraft(app)
assert.match(draft.reference,/^WINTER-2026-[a-f0-9]{32}$/)
assert.equal(createApplicationDraft({...app,fileName:'renamed.xlsx'}).reference,draft.reference,'same bytes keep reference across file names/devices')
assert.notEqual(createApplicationDraft({...app,digest:'b'.repeat(64)}).reference,draft.reference,'revision gets an independent stable retry namespace')
assert.equal(readApplicationDraft({...draft,reference:'LEGACY-REF'}).reference,'LEGACY-REF','existing saved identifiers are never rewritten')
let todos=applicationTodos(draft,false)
assert(todos.some(x=>x.target==='application-club'&&x.blocking))
assert(todos.some(x=>x.target===applicationPersonTarget('r1')&&x.blocking))
assert(todos.some(x=>x.target==='application-payment'&&x.blocking))
const original=structuredClone(draft.original)
draft.edited.people[1].reading='';draft.edited.entries[0].rider='';draft.edited.amounts.total='1'
todos=applicationTodos(draft,true)
assert(todos.some(x=>x.target===applicationPersonTarget('h1')&&!x.blocking),'reading warning remains advisory')
assert(todos.some(x=>x.target===applicationEntryTarget(draft.edited.entries[0].key)&&x.blocking),'entry errors point to the actual Excel row')
assert(todos.some(x=>x.target==='application-amount-total'&&x.blocking))
assert.deepEqual(draft.original,original,'guide only reads; does not correct source or assume payment')
const env=setup(),s=env.snapshot,d=env.work.review
assert.equal(applicationClubSummary(d,s).state,'new')
const rider=env.addPerson({kind:'rider',name:'合成選手',reading:'ごうせいせんしゅ',jefNumber:'',clubName:d.edited.club})
assert.equal(applicationClubSummary(d,s).state,'known','a common roster club is not yet tournament registration')
const club=s.roster.clubs[0]
env.publish(club.id,[rider],[])
assert.equal(applicationClubSummary(d,s).state,'registered')
s.data.entries.push({entry_id:'synthetic',organization_id:s.data.organizations[0].id,competition_no:'5',rider_id:s.data.riders[0].id,horse_id:'unknown',status:'wd'})
assert.equal(applicationClubSummary(d,s).entries[0].status,'棄権済み','withdrawals must not look like new entries')
const legacy=structuredClone(s);legacy.roster={clubs:[],entities:[],affiliations:[],participants:[]}
assert.equal(applicationClubSummary(d,legacy).state,'registered','legacy tournament organizations are also displayed as registered')
const variant=structuredClone(d);variant.edited.club=' '+d.edited.club.split('').join(' ')+' '
assert.equal(applicationClubSummary(variant,s).state,'ambiguous','similar names are surfaced without merging clubs')
s.roster.clubs.push({...club,id:'duplicate'})
assert.equal(applicationClubSummary(d,s).state,'ambiguous')
console.log('PASS: deterministic automatic references, legacy preservation, targeted issue navigation, warning severity, registered/common/legacy/ambiguous club states; read-only synthetic fixtures')
